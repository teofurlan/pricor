"""Synthetic sample price lists shipped with the package (see README.md in this folder).

Everything here is generated by `tools/samples/generate.py`: a fictional distributor with no
third-party data. The files are package data, so they travel with the wheel.
"""

from dataclasses import dataclass
from pathlib import Path

SAMPLES_DIR = Path(__file__).resolve().parent
XLSX_CONTENT_TYPE = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
SUPPLIER_NAME = "Distribuidora Ejemplo"


@dataclass(frozen=True)
class Sample:
    id: str
    file_name: str
    supplier_name: str
    week: int
    title: dict[str, str]  # by interface language
    description: dict[str, str]

    @property
    def path(self) -> Path:
        return SAMPLES_DIR / self.file_name


SAMPLES: tuple[Sample, ...] = (
    Sample(
        id="distribuidora-ejemplo-semana-1",
        file_name="distribuidora-ejemplo-semana-1.xlsx",
        supplier_name=SUPPLIER_NAME,
        week=1,
        title={"en": "Example distributor, week 1", "es": "Distribuidora Ejemplo, semana 1"},
        description={
            "en": "About 300 hardware and electrical products with section rows, mixed currencies and discounts.",
            "es": "Unos 300 productos de ferretería y electricidad con rubros, monedas mixtas y descuentos.",
        },
    ),
    Sample(
        id="distribuidora-ejemplo-semana-2-simulada",
        file_name="distribuidora-ejemplo-semana-2-simulada.xlsx",
        supplier_name=SUPPLIER_NAME,
        week=2,
        title={
            "en": "Example distributor, week 2 (simulated)",
            "es": "Distribuidora Ejemplo, semana 2 (simulada)",
        },
        description={
            "en": "The following week, simulated: price changes, new and dropped products, one suspicious price.",
            "es": "La semana siguiente, simulada: cambios de precios, productos nuevos y dados de baja, un precio sospechoso.",
        },
    ),
)


def find_sample(sample_id: str) -> Sample | None:
    return next((sample for sample in SAMPLES if sample.id == sample_id), None)
